'use strict';

const ExcelJS = require('exceljs');
const { outcomeLabel } = require('./service');

function csvEscape(v) {
  if (v == null) return '';
  let s = String(v);
  // Neutralise spreadsheet formula injection.
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

function toCsv(headers, rows) {
  return '﻿' + [headers, ...rows].map((r) => r.map(csvEscape).join(',')).join('\r\n') + '\r\n';
}

function addr(a) {
  if (!a) return '';
  return [a.line1, a.line2, a.line3, a.line4, a.line5, a.postcode, a.countryCode].filter(Boolean).join(', ');
}

const RESULT_HEADERS = ['Row', 'Client ref', 'Client name', 'VAT number (as supplied)', 'VAT number (checked)', 'Outcome', 'HMRC registered name',
  'Name match', 'Name score', 'HMRC address', 'HMRC consultation number', 'HMRC processing date', 'Checked at (UTC)', 'Source',
  'Notes', 'Review', 'Review note', 'Reviewed by', 'Reviewed at'];

function resultRow(c) {
  return [c.row_number, c.client_ref, c.client_name, c.input_vrn, c.vrn ? `GB${c.vrn}` : '', outcomeLabel(c), c.hmrc_name,
    c.name_level === 'not_provided' ? 'No client name supplied' : c.name_level, c.name_score, addr(c.hmrc_address), c.consultation_number,
    c.processing_date, c.checked_at, c.source, c.format_reason || c.message, c.review_status, c.review_note, c.reviewed_by, c.reviewed_at];
}

function batchCsv(batch, checks) {
  return toCsv(RESULT_HEADERS, checks.map(resultRow));
}

function auditCsv(events) {
  return toCsv(['Seq', 'Timestamp (UTC)', 'User', 'Action', 'Entity type', 'Entity ID', 'Details', 'Previous hash', 'Hash'],
    events.map((e) => [e.seq, e.ts, e.actor, e.action, e.entity_type, e.entity_id, e.details ? JSON.stringify(e.details) : '', e.prev_hash, e.hash]));
}

const NAVY = 'FF0E1640';
async function evidenceWorkbook({ batch, checks, events, verify, cfg, generatedBy }) {
  const wb = new ExcelJS.Workbook();
  wb.creator = `${cfg.firmName} VAT Registration Checker`;
  wb.created = new Date();

  const s = wb.addWorksheet('Summary', { properties: { tabColor: { argb: NAVY } } });
  s.columns = [{ width: 34 }, { width: 80 }];
  s.addRow([`${cfg.firmName} — VAT registration check evidence`]).font = { bold: true, size: 16, color: { argb: NAVY } };
  s.addRow([]);
  const meta = [
    ['Batch ID', batch.id], ['Batch name', batch.name], ['Source file', batch.source_filename],
    ['Source file SHA-256', batch.file_sha256], ['Uploaded by', batch.created_by], ['Uploaded at (UTC)', batch.created_at],
    ['Checks completed at (UTC)', batch.completed_at || 'In progress'],
    ['Data source', batch.mode === 'simulation' ? 'SIMULATION — not real HMRC data' : `HMRC Check a UK VAT number API v2.0 (${batch.mode})`],
    ['Requester VRN (for consultation numbers)', batch.requester_vrn ? `GB${batch.requester_vrn}` : 'Not configured'],
    ['Rows', batch.total], ['Registered', batch.registered], ['Not registered', batch.not_registered],
    ['Invalid format', batch.invalid_format], ['Technical errors', batch.errors], ['Name mismatches', batch.name_mismatch],
    ['Outstanding items needing review', batch.attention],
    ['Results fingerprint (SHA-256)', batch.results_sha256 || 'Pending'],
    ['Audit trail integrity', verify.ok ? `Verified intact — ${verify.count} events, head ${verify.headHash}` : `FAILED — ${verify.reason}`],
    ['Evidence pack generated by', generatedBy], ['Evidence pack generated at (UTC)', new Date().toISOString()],
  ];
  meta.forEach(([k, v]) => {
    const r = s.addRow([k, v == null ? '' : v]);
    r.getCell(1).font = { bold: true };
  });

  const r = wb.addWorksheet('Results', { views: [{ state: 'frozen', ySplit: 1 }] });
  r.addRow(RESULT_HEADERS);
  checks.forEach((c) => r.addRow(resultRow(c)));
  r.getRow(1).eachCell((cell) => {
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY } };
  });
  r.columns.forEach((col, i) => { col.width = [6, 14, 30, 18, 16, 30, 34, 12, 10, 44, 22, 24, 24, 12, 40, 10, 30, 18, 24][i] || 16; });
  r.autoFilter = { from: 'A1', to: { row: 1, column: RESULT_HEADERS.length } };

  const a = wb.addWorksheet('Audit trail', { views: [{ state: 'frozen', ySplit: 1 }] });
  a.addRow(['Seq', 'Timestamp (UTC)', 'User', 'Action', 'Entity', 'Details', 'Hash']);
  events.slice().reverse().forEach((e) => a.addRow([e.seq, e.ts, e.actor, e.action, `${e.entity_type || ''} ${e.entity_id || ''}`.trim(), e.details ? JSON.stringify(e.details) : '', e.hash]));
  a.getRow(1).font = { bold: true };
  a.columns.forEach((col, i) => { col.width = [7, 26, 22, 20, 22, 90, 66][i]; });

  return wb.xlsx.writeBuffer();
}

async function templateWorkbook() {
  const wb = new ExcelJS.Workbook();
  const s = wb.addWorksheet('Clients');
  s.addRow(['Client ref', 'Client name', 'VAT number']);
  s.addRow(['C001', 'Example Trading Ltd', 'GB123456782']);
  s.getRow(1).font = { bold: true };
  s.columns = [{ width: 14 }, { width: 40 }, { width: 18 }];
  return wb.xlsx.writeBuffer();
}

module.exports = { batchCsv, auditCsv, evidenceWorkbook, templateWorkbook, toCsv };
